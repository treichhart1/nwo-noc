import {test,expect} from '@playwright/test'
import fs from 'node:fs'
test.skip(process.env.NOC89_ANALYTICS_BROWSER!=='true','Requires explicit offline historical analytics fixture')
test('RF analytics filters, evidence, scores and historical comparisons remain read-only',async({page})=>{
 const state=process.env.NOC_ACCEPTANCE_STATE!
 const env=Object.fromEntries(fs.readFileSync(`${state}/acceptance.env`,'utf8').trim().split('\n').map(line=>{const i=line.indexOf('=');return [line.slice(0,i),line.slice(i+1)]}))
 const fixture=JSON.parse(fs.readFileSync(`${state}/analytics-devices.json`,'utf8'))
 const external:string[]=[]
 await page.route('**/*',async route=>{if(new URL(route.request().url()).origin!=='http://127.0.0.1:18090'){external.push(route.request().url());await route.abort()}else await route.continue()})
 await page.goto('/');await page.locator('.loginCard input').nth(0).fill('acceptance');await page.locator('input[type=password]').fill(env.ADMIN_PASSWORD)
 await page.getByRole('button',{name:'Sign in',exact:true}).click()
 await page.locator('nav').getByRole('button',{name:'RF Analytics',exact:true}).click()
 const panel=page.getByRole('region',{name:'Historical RF analytics',exact:true})
 await page.getByLabel('Analytics window',{exact:true}).selectOption('30d')
 await page.getByLabel('Analytics vendor',{exact:true}).selectOption('cambium')
 await page.getByLabel('Analytics site',{exact:true}).selectOption(String(fixture.site_ids.interference))
 await page.getByLabel('Analytics device',{exact:true}).selectOption(String(fixture.device_ids.interference))
 await expect(panel).toContainText('suspected_interference')
 await expect(panel).toContainText('noise_snr_pattern')
 await expect(panel).toContainText('Confidence: high')
 const detail=page.getByRole('region',{name:'Device historical RF analysis'})
 await expect(detail).toContainText('Score contributions')
 await expect(detail).toContainText('Historical comparisons')
 await expect(detail).toContainText('1h');await expect(detail).toContainText('30d')
 await page.getByLabel('Analytics chart metric',{exact:true}).selectOption('noise_floor_dbm')
 await expect(detail.getByRole('img',{name:'Noise floor (dBm) analytics history',exact:true})).toBeVisible()
 await page.getByLabel('Analytics chart metric',{exact:true}).selectOption('health_score')
 await expect(detail.getByRole('img',{name:'Available-metric health score analytics history',exact:true})).toBeVisible()
 await page.getByLabel('Analytics site',{exact:true}).selectOption('')
 await page.getByLabel('Analytics device',{exact:true}).selectOption(String(fixture.device_ids.congestion))
 await expect(panel).toContainText('likely_congestion')
 await page.getByLabel('Analytics device',{exact:true}).selectOption(String(fixture.device_ids.missing))
 await expect(panel).toContainText('partial_telemetry')
 await expect(panel).toContainText('Missing expected metrics:')
 await page.getByLabel('Analytics device',{exact:true}).selectOption(String(fixture.device_ids.recurring))
 await expect(panel).toContainText('20:00 America/New_York')
 if(fixture.microwave_link_ids.length){
  await page.getByLabel('Analytics device',{exact:true}).selectOption('')
  await page.getByLabel('Analytics vendor',{exact:true}).selectOption('')
  await page.getByLabel('Analytics link',{exact:true}).selectOption(String(fixture.microwave_link_ids[0]))
  await expect(panel).toContainText('microwave:c1')
 }
 expect(external).toEqual([])
})
