import {test,expect} from '@playwright/test'
import fs from 'node:fs'
test.skip(process.env.NOC90_TROUBLESHOOTING_BROWSER!=='true','Requires explicit offline synthetic analytics fixture')
test('RF troubleshooting evidence, deduplication, operator notes, lifecycle and disabled AI',async({page})=>{
 const state=process.env.NOC_ACCEPTANCE_STATE!
 const env=Object.fromEntries(fs.readFileSync(`${state}/acceptance.env`,'utf8').trim().split('\n').map(line=>{const i=line.indexOf('=');return [line.slice(0,i),line.slice(i+1)]}))
 const fixture=JSON.parse(fs.readFileSync(`${state}/analytics-devices.json`,'utf8'))
 const external:string[]=[]
 await page.route('**/*',async route=>{if(new URL(route.request().url()).origin!=='http://127.0.0.1:18090'){external.push(route.request().url());await route.abort()}else await route.continue()})
 await page.goto('/');await page.locator('.loginCard input').nth(0).fill('acceptance');await page.locator('input[type=password]').fill(env.ADMIN_PASSWORD)
 await page.getByRole('button',{name:'Sign in',exact:true}).click()
 await page.locator('nav').getByRole('button',{name:'RF Troubleshooting',exact:true}).click()
 const panel=page.getByRole('region',{name:'RF troubleshooting',exact:true})
 await page.getByLabel('Troubleshooting device',{exact:true}).selectOption(String(fixture.device_ids.interference))
 const evaluation=page.waitForResponse(r=>r.url().endsWith('/api/rf/troubleshooting/evaluate')&&r.request().method()==='POST')
 await page.getByRole('button',{name:'Evaluate stored evidence',exact:true}).click()
 const evaluated=await evaluation;expect(evaluated.status(),await evaluated.text()).toBe(200)
 const review=panel.getByRole('button',{name:/Review recommendation #/})
 await expect(review.first()).toBeVisible();const count=await review.count()
 await page.getByRole('button',{name:'Evaluate stored evidence',exact:true}).click()
 await expect(review).toHaveCount(count)
 await expect(panel.getByRole('alert')).toHaveCount(0)
 await review.first().click()
 const detail=page.getByRole('article',{name:'Recommendation detail'})
 await expect(detail).toContainText('unconfirmed')
 await expect(detail).toContainText('telemetry_samples:')
 await expect(detail).toContainText('Potential', {ignoreCase:true})
 await page.getByRole('button',{name:'Check explanation availability'}).click()
 await expect(detail).toContainText('Explanation provider: disabled')
 await page.getByLabel('Next recommendation status',{exact:true}).selectOption('reviewed')
 await page.getByLabel('Technician note',{exact:true}).fill('Synthetic technician <script>window.injected=true</script> review; no equipment changes')
 await page.getByRole('button',{name:'Save operator review',exact:true}).click()
 await expect(detail).toContainText('rf.troubleshooting.workflow')
 await expect(detail).toContainText('<script>window.injected=true</script>')
 expect(await page.evaluate(()=>Object.hasOwn(window,'injected'))).toBe(false)
 await page.getByLabel('Next recommendation status',{exact:true}).selectOption('investigating')
 await page.getByRole('button',{name:'Save operator review',exact:true}).click()
 await expect(detail).toContainText('investigating')
 await page.getByLabel('Next recommendation status',{exact:true}).selectOption('resolved')
 await page.getByLabel('Resolution documentation',{exact:true}).fill('Synthetic evidence reviewed; technician confirmation remains a release gate; no actions executed')
 await page.getByRole('button',{name:'Save operator review',exact:true}).click()
 await expect(detail).toContainText('Resolution: Synthetic evidence reviewed')
 await page.getByLabel('Next recommendation status',{exact:true}).selectOption('closed')
 await page.getByRole('button',{name:'Save operator review',exact:true}).click()
 await expect(detail).toContainText('closed')
 expect(external).toEqual([])
})
