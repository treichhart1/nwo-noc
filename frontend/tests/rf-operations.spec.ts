import {test,expect} from '@playwright/test'
import fs from 'node:fs'
test.skip(process.env.NOC91_OPERATIONS_BROWSER!=='true','Requires explicit offline RF operations fixture')
const state=process.env.NOC_ACCEPTANCE_STATE!
const env=()=>Object.fromEntries(fs.readFileSync(`${state}/acceptance.env`,'utf8').trim().split('\n').map(line=>{const i=line.indexOf('=');return [line.slice(0,i),line.slice(i+1)]}))
test.beforeEach(async({page})=>{
 const external:string[]=[]
 await page.route('**/*',async route=>{if(new URL(route.request().url()).origin!=='http://127.0.0.1:18090'){external.push(route.request().url());await route.abort()}else await route.continue()})
 page.on('close',()=>expect(external).toEqual([]))
 page.on('pageerror',error=>{throw error})
 await page.goto('/');await page.locator('.loginCard input').nth(0).fill('acceptance');await page.locator('input[type=password]').fill(env().ADMIN_PASSWORD)
 await page.getByRole('button',{name:'Sign in',exact:true}).click()
 await page.locator('nav').getByRole('button',{name:'RF Operations',exact:true}).click()
 await expect(page.getByRole('region',{name:'Unified RF operations',exact:true})).toContainText('Manual refresh')
})
test('unified RF filters, shared incident assignment and closure, recommendations, link history and no background polling',async({page})=>{
 test.setTimeout(150000)
 const analytics=JSON.parse(fs.readFileSync(`${state}/analytics-devices.json`,'utf8'))
 const fixture=JSON.parse(fs.readFileSync(`${state}/operations-devices.json`,'utf8'))
 const panel=page.getByRole('region',{name:'Unified RF operations',exact:true})
 const requests:string[]=[];page.on('request',r=>{if(r.url().includes('/api/'))requests.push(r.url())})
 await page.getByLabel('RF site filter',{exact:true}).selectOption(String(analytics.site_ids.interference))
 await page.getByLabel('RF vendor filter',{exact:true}).selectOption('cambium')
 await page.getByLabel('RF device or link search',{exact:true}).fill('NOC89 Synthetic interference')
 await page.getByLabel('RF time range',{exact:true}).selectOption('30d')
 expect(requests.filter(r=>r.includes('/rf/operations?'))).toHaveLength(0)
 await page.getByRole('button',{name:'Apply RF filters',exact:true}).click()
 await expect(panel).toContainText('1 matching devices')
 await expect(panel).toContainText('noise_snr_pattern')
 await expect(panel).toContainText('suspected interference')
 await page.getByText('Historical RF comparisons for this device page (30d)',{exact:true}).click()
 await expect(page.getByRole('region',{name:'RF historical comparisons',exact:true})).toContainText('Baseline median')
 const key=`rf-analytics:device:${analytics.device_ids.interference}`
 await page.getByRole('button',{name:`Acknowledge ${key}`,exact:true}).click()
 await expect(panel).toContainText('this observed evidence acknowledged')
 const opened=page.waitForResponse(r=>r.url().endsWith('/api/rf/operations/alerts/review')&&r.request().method()==='POST')
 await page.getByRole('button',{name:`Open investigation ${key}`,exact:true}).click()
 const response=await opened;expect(response.status(),await response.text()).toBe(200)
 const id=(await response.json()).incident.id
 const detail=page.getByRole('article',{name:'Technician investigation',exact:true})
 await expect(detail).toContainText(`Investigation #${id}`)
 await page.getByLabel('Assigned technician',{exact:true}).selectOption(String(fixture.technician_id))
 await page.getByLabel('Investigation status',{exact:true}).selectOption('investigating')
 await page.getByLabel('Technician findings',{exact:true}).fill('Synthetic RF evidence needs independent technician confirmation')
 await page.getByLabel('Investigation note',{exact:true}).fill('Synthetic technician <script>window.injected=true</script> note')
 await page.getByRole('button',{name:'Save investigation',exact:true}).click()
 await expect(detail).toContainText('incident.update')
 await expect(detail).toContainText('<script>window.injected=true</script>')
 expect(await page.evaluate(()=>Object.hasOwn(window,'injected'))).toBe(false)
 await expect(page.getByLabel('Assigned technician',{exact:true})).toHaveValue(String(fixture.technician_id))
 await page.getByLabel('Investigation status',{exact:true}).selectOption('resolved')
 await page.getByLabel('Investigation resolution',{exact:true}).fill('Synthetic investigation documented; no equipment changes')
 await page.getByRole('button',{name:'Save investigation',exact:true}).click()
 await expect(page.getByLabel('Investigation status',{exact:true})).toHaveValue('resolved')
 await page.getByLabel('Investigation status',{exact:true}).selectOption('closed')
 await page.getByRole('button',{name:'Save investigation',exact:true}).click()
 await expect(page.getByLabel('Investigation status',{exact:true})).toHaveValue('closed')
 await expect(detail).toContainText('Complete audit history')
 await page.getByRole('group',{name:'RF operations views'}).getByRole('button',{name:'network',exact:true}).click()
 await page.getByRole('button',{name:`Troubleshoot #${analytics.device_ids.interference}`,exact:true}).click()
 const rec=page.getByRole('region',{name:'RF troubleshooting',exact:true})
 await expect(rec.getByRole('button',{name:/Review recommendation #/}).first()).toBeVisible()
 // Reproduce the stale-card window deterministically; users must only be able to open the filtered results.
 await page.route(url=>url.origin==='http://127.0.0.1:18090'&&url.pathname==='/api/rf/troubleshooting',async route=>{if(new URL(route.request().url()).searchParams.get('status')==='new')await new Promise(resolve=>setTimeout(resolve,300));await route.continue()})
 await rec.getByLabel('Recommendation filter',{exact:true}).selectOption('new')
 await rec.getByRole('button',{name:/Review recommendation #/}).first().click()
 await expect(rec.getByRole('article',{name:'Recommendation detail'})).toContainText('· new ·')
 await rec.getByLabel('Next recommendation status',{exact:true}).selectOption('acknowledged')
 await rec.getByRole('button',{name:'Save operator review',exact:true}).click()
 await expect(rec.getByRole('article',{name:'Recommendation detail'})).toContainText('acknowledged')
 await page.getByRole('button',{name:'Clear RF filters',exact:true}).click()
 await page.getByLabel('RF device or link search',{exact:true}).fill(String(analytics.microwave_link_ids[0]))
 await page.getByRole('button',{name:'Apply RF filters',exact:true}).click()
 await page.getByRole('group',{name:'RF operations views'}).getByRole('button',{name:'links',exact:true}).click()
 await page.getByRole('button',{name:`Inspect link #${analytics.microwave_link_ids[0]}`,exact:true}).click()
 const link=page.getByRole('article',{name:'RF link detail',exact:true})
 await expect(link).toContainText('Reported alarms')
 await expect(link).toContainText('Modulation (bits/symbol)')
 await expect(link.getByRole('img',{name:'Signal / RSL (dBm) analytics history',exact:true}).first()).toBeVisible()
 await page.getByLabel('Link chart metric',{exact:true}).selectOption('snr_db')
 await expect(link.getByRole('img',{name:'SNR (dB) analytics history',exact:true}).first()).toBeVisible()
 await expect(panel.getByRole('alert')).toHaveCount(0)
 // Root legacy polling is suspended in this view; no hidden 30-second fetch fan-out.
 const before=requests.length;await page.waitForTimeout(32000)
 expect(requests.slice(before).filter(r=>/\/api\/(dashboard|rf\/operations\?)/.test(r))).toEqual([])
})
test('responsive empty, stale and missing RF evidence stays explicit',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 const panel=page.getByRole('region',{name:'Unified RF operations',exact:true})
 await page.getByLabel('RF device or link search',{exact:true}).fill('NOC91 Synthetic stale')
 await page.getByRole('button',{name:'Apply RF filters',exact:true}).click()
 await expect(panel).toContainText('1 matching devices')
 await expect(panel).toContainText('stale')
 await expect(panel).toContainText('unknown')
 await page.getByLabel('RF device or link search',{exact:true}).fill('NOC91 Synthetic missing')
 await page.getByRole('button',{name:'Apply RF filters',exact:true}).click()
 await expect(panel).toContainText('1 matching devices')
 await expect(panel).toContainText('missing')
 await page.getByLabel('RF device or link search',{exact:true}).fill('does-not-exist-synthetic')
 await page.getByRole('button',{name:'Apply RF filters',exact:true}).click()
 await expect(panel).toContainText('0 matching devices')
 await expect(panel).toContainText('No devices match the filters')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBe(true)
})
